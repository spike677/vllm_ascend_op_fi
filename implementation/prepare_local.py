"""One-time derivation of a new experiment; never edits its parent control."""
from pathlib import Path

ROOT=Path(__file__).resolve().parent

def edit(path,old,new):
    text=path.read_text(encoding='utf-8')
    assert text.count(old)==1,(path,old[:80],text.count(old))
    path.write_text(text.replace(old,new),encoding='utf-8',newline='\n')

def main():
    policy=ROOT/'source_policy/fault28_fia_policy.h'
    edit(policy,'inline State Select(','''inline bool Replay(const State& s) {
    return s.eligible && s.selectedM == 128 && s.mode.find("replay") != std::string::npos;
}
inline State Select(''')
    edit(policy,'"batch_coupled_m32"};','"batch_coupled_m32", "batch_coupled_replay_m128", "coupled_replay_m128"};')
    edit(ROOT/'vendor_exec.py',"'batch_coupled_m32'),", "'batch_coupled_m32','batch_coupled_replay_m128','coupled_replay_m128'),")
    host=ROOT/'build_host.py'
    edit(host,"cpp=once(cpp,old,new)",'''cpp=once(cpp,old,new)
    cpp=once(cpp,'    if ((SetNumBlocks(numBlocks_) != ge::GRAPH_SUCCESS) ||',\'''    // A distinct compiled template changes only the online denominator update.
    // All M/S2/workspace/partition fields were generated by native host above.
    if (fault28_fia::Replay(fault28State_)) {
        if (tilingKey_ != 109000000000400000ULL || mBaseSize_ != 128 || sInnerSize_ != 128) {
            OP_LOGE(fiaInfo_->opName, "Denominator replay requires the validated M128/S2=128 BRC template.");
            return ge::GRAPH_FAILED;
        }
        tilingKey_ = 119000000000400000ULL;
    }
    if ((SetNumBlocks(numBlocks_) != ge::GRAPH_SUCCESS) ||\''')''')
    edit(host,"'dcat-f28-visible-host-a1'","'dcat-f28-replay-host-a1'")
    edit(host,'The original\nofficial kernel binary is retained.','The inherited private kernel is retained during host staging; a separate build\nthen adds the denominator replay template before execution is allowed.')
    public=ROOT/'analysis/public_plan.py'
    edit(public,"'109000000000400000'),","'109000000000400000','119000000000400000'),")
    edit(public,"key.startswith('109')==prune", "(key.startswith('109') or key.startswith('119'))==prune")
    edit(public,"digest=hashlib.sha256(raw).hexdigest()",'''replay=key=='119000000000400000'
        require(not replay or (fields['innerSplitParams.mBaseSize']==128 and fields['innerSplitParams.s2BaseSize']==128),
                'Replay outside its compiled geometry')
        digest=hashlib.sha256(raw).hexdigest()''')
    edit(public,"'actual_host_key':key,'mode':event['mode']", "'actual_host_key':key,'denominator_replay':replay,'mode':event['mode']")
    edit(public,"'unmasked_key_coverage':'all target queries exactly once'", "'unmasked_key_coverage':'all target queries score/PV keys exactly once; see actual key for deliberate denominator replay'")
    # The old generic runner is retained only as a bounded controller helper.
    # New experiment entrypoint never calls its search/old acceptance matrix.
    edit(ROOT/'run_search.py',"'causal_base512',capture=False)","'coupled_m128',capture=False)")

if __name__=='__main__':main()
